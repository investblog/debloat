/** Content script match patterns for Google Search result pages */
export const googleSearchMatches = (hosts: string[]): string[] => hosts.map((h) => `*://${h}/search*`);

/** Origins for permissions.request / host_permissions (any subdomain of each extra domain) */
export const googleOrigins = (domains: string[]): string[] => domains.map((d) => `*://*.${d}/*`);
